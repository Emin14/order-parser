const { test } = require('node:test');
const assert = require('node:assert/strict');
require('tsx/cjs');
const { formatCollectionBlocks } = require('../src/utils/collection.ts');

const block = (date, time, text) => ({ date, time, text });
const monday = (hour = 10) => new Date(2026, 10, 2, hour);
const format = (blocks, now = monday()) => formatCollectionBlocks(blocks, now);

test('Аркада: переход к понедельничному сбору происходит в субботу вечером', () => {
    const blocks = [
        block('31.10', '11:21', 'Заказ на сегодня\nАвокадо 10 шт'),
        block('31.10', '20:45', 'Лимон 3кг\nАпельсины 15 кг'),
        block('01.11', '15:51', 'Если можно к открытию\nРомано 1 кор')
    ];
    const expected = '(сб 31.10 11:21)\nЗаказ на сегодня\nАвокадо 10 шт\n\n' +
        '(сб 31.10 20:45)\nЛимон 3кг\nАпельсины 15 кг\n\nЕсли можно к открытию\nРомано 1 кор';
    for (const now of [new Date(2026, 10, 1, 23), monday(0), monday(10), monday(17)]) {
        assert.equal(format(blocks, now), expected);
    }
});

test('Граница отображения — суббота 15:00, а не 18:00', () => {
    assert.equal(format([
        block('31.10', '14:59', 'Старое'), block('31.10', '15:00', 'Актуальное'),
        block('31.10', '18:00', 'Добавка'), block('01.11', '11:00', 'Ещё')
    ]), '(сб 31.10 14:59)\nСтарое\n\n(сб 31.10 15:00)\nАктуальное\n\nДобавка\n\nЕщё');
});

test('Без старой части субботний вечер и воскресенье не получают отметок', () => {
    assert.equal(format([
        block('31.10', '15:00', 'Заказ'), block('01.11', '11:00', 'Добавка'),
        block('01.11', '23:16', 'Ещё')
    ]), 'Заказ\n\nДобавка\n\nЕщё');
});

test('Старая часть и переход к актуальной получают собственные отметки', () => {
    assert.equal(format([
        block('31.10', '14:10', 'Хорошо'), block('31.10', '20:45', 'Заказ')
    ]), '(сб 31.10 14:10)\nХорошо\n\n(сб 31.10 20:45)\nЗаказ');
});

test('Старый город: при переходе сразу к воскресенью ставится одна отметка', () => {
    const blocks = [block('31.10', '14:10', 'Хорошо'), block('01.11', '23:16', 'Заказ')];
    assert.equal(format(blocks, monday()), '(сб 31.10 14:10)\nХорошо\n\n(вс 01.11 23:16)\nЗаказ');
    assert.equal(format(blocks, new Date(2026, 10, 1, 23)), '(сб 31.10 14:10)\nХорошо\n\n(23:16)\nЗаказ');
});

test('Переход в актуальную часть ночью тоже обозначается', () => {
    assert.equal(format([
        block('31.10', '11:21', 'Старое'), block('01.11', '00:10', 'Новое'),
        block('01.11', '20:45', 'Добавка')
    ]), '(сб 31.10 11:21)\nСтарое\n\n(вс 01.11 00:10)\nНовое\n\nДобавка');
});

test('Понедельник с 18:00 больше не использует период выходных', () => {
    assert.equal(format([block('31.10', '20:45', 'Суббота'), block('01.11', '23:16', 'Воскресенье')], monday(18)),
        '(сб 31.10 20:45)\nСуббота\n\n(23:16)\nВоскресенье');
});

test('Будни: утренний блок и первое вечернее продолжение', () => {
    assert.equal(format([
        block('03.11', '14:10', 'Утро'), block('03.11', '23:16', 'Вечер'), block('03.11', '23:17', 'Добавка')
    ], new Date(2026, 10, 3, 23)), '(14:10)\nУтро\n\n(23:16)\nВечер\n\nДобавка');
});

test('Будни: отдельные вечерние и ночные заказы без времени', () => {
    const now = new Date(2026, 10, 3, 23);
    assert.equal(format([block('03.11', '23:16', 'Заказ')], now), 'Заказ');
    assert.equal(format([block('03.11', '05:59', 'Ночь')], now), 'Ночь');
});

test('Будни: вчерашний вечер после полуночи без времени', () => {
    assert.equal(format([block('02.11', '17:38', 'Заказ')], new Date(2026, 10, 3, 0, 5)), 'Заказ');
});

test('Каждое старое сообщение получает дату, время и день недели', () => {
    assert.equal(format([
        block('30.10', '11:00', 'Раз'), block('30.10', '12:00', 'Два')
    ]), '(пт 30.10 11:00)\nРаз\n\n(пт 30.10 12:00)\nДва');
});

test('Отдельная накладная и обычное продолжение получают собственную дату', () => {
    const original = block('31.10', '11:21', 'Авокадо 10 шт');
    assert.equal(format([original]),
        '(сб 31.10 11:21)\nАвокадо 10 шт');
    assert.equal(format([block('31.10', '11:21', 'Морковь 15 кг')]),
        '(сб 31.10 11:21)\nМорковь 15 кг');
    assert.equal(format([block('31.10', '12:00', 'Продолжение')]),
        '(сб 31.10 12:00)\nПродолжение');
});

test('Отдельная накладная не заставляет показывать время у актуального вечернего заказа', () => {
    assert.equal(format([
        block('31.10', '20:45', 'Морковь 15 кг')
    ]), 'Морковь 15 кг');
    assert.equal(format([
        block('03.11', '14:10', 'Морковь 15 кг')
    ], new Date(2026, 10, 3, 23)), '(14:10)\nМорковь 15 кг');
});

test('День недели правильно определяется на границе года', () => {
    assert.equal(format([block('31.12', '11:00', 'Заказ')], new Date(2027, 0, 3, 23)),
        '(чт 31.12 11:00)\nЗаказ');
});
